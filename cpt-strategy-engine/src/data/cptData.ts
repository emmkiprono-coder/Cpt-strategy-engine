export function calculateRevenue(
  code: CPTCode,
  volume: number,
  payerMix: { medicare: number; commercial: number; medicaid: number }
): { total: number; perUnit: number; breakdown: Record<string, number> } {
  const medicareRev = code.medicareRate * volume * (payerMix.medicare / 100);
  const commercialRev = code.medicareRate * code.commercialMultiplier * volume * (payerMix.commercial / 100);
  const medicaidRev = code.medicareRate * 0.72 * volume * (payerMix.medicaid / 100);
  const total = medicareRev + commercialRev + medicaidRev;
  return {
    total,
    perUnit: total / volume,
    breakdown: { medicare: medicareRev, commercial: commercialRev, medicaid: medicaidRev },
  };
}

export function getCodesByServiceLine(serviceLineId: string): CPTCode[] {
  return CPT_DATABASE.filter((c) => c.serviceLine === serviceLineId);
}

export function getCodeByNumber(code: string): CPTCode | undefined {
  return CPT_DATABASE.find((c) => c.code === code);
}
